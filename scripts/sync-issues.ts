// Files or updates one GitHub issue per problem in #4471, from the same code the kb page runs.
//   node scripts/sync-issues.ts           create or update the issues, write src/lib/data/tickets.json
//   node scripts/sync-issues.ts --check   exit 1 when an issue no longer matches the data
// Needs gh signed in (or GH_TOKEN in CI). Repo: GITHUB_REPOSITORY, else the current gh repo.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import type { Report, Tenant } from '../src/lib/kb/causes.ts';
import { PROBLEM_INFO, PROBLEMS, splitTicket, type Problem, type ProblemGroup } from '../src/lib/kb/problems.ts';

const DATA = new URL('../src/lib/data/', import.meta.url);
const read = (path: string) => JSON.parse(fs.readFileSync(new URL(path, DATA), 'utf8'));
const TICKET = 4471;
const PAGE = 'src/routes/kb/incidents/4471/split/+page.svx';

const reports: Report[] = read('reports-4471.json');
const notes: { oneDayMove: string[] } = read('desk-notes.json');
const tenants = new Map<string, Tenant>(
  fs.readdirSync(new URL('tenants/', DATA)).map((f) => {
    const t: Tenant = read(`tenants/${f}`);
    return [t.handle, t];
  }),
);
const split = splitTicket(reports, (r) => tenants.get(r.tenant), notes.oneDayMove, TICKET);

const gh = (...args: string[]) => execFileSync('gh', args, { encoding: 'utf8' });
const repo = process.env.GITHUB_REPOSITORY ?? JSON.parse(gh('repo', 'view', '--json', 'nameWithOwner')).nameWithOwner;
const label = (p: Problem) => `problem:${p}`;

function titleOf(g: ProblemGroup): string {
  return `#${TICKET} · ${g.problem}: ${PROBLEM_INFO[g.problem].title} (${g.reports.length} reports)`;
}

function bodyOf(g: ProblemGroup): string {
  const channels = Object.entries(g.channels).sort((a, b) => b[1] - a[1]).map(([c, n]) => `${c} ${n}`).join(', ');
  const rows = g.reports.map((r) => `| ${r.id} | ${r.tenant} | ${r.channel} | ${r.receivedAt.slice(0, 10)} | ${r.body.replaceAll('|', '\\|')} |`);
  return [
    `Split out of support ticket #${TICKET} (merged as one issue, marked known).`,
    '',
    `**Reports covered: ${g.reports.length}** of the ${split.total} unique reports merged into #${TICKET}.`,
    '',
    PROBLEM_INFO[g.problem].what,
    '',
    ...Object.entries(g.alsoIn).map(([q, n]) => `- ${n} of these are also counted under \`${q}\`: the desk files each report by tenant and counts it again where it read it differently (\`readAs\` in \`causes.ts\`).`),
    `- Tenants: ${g.tenants} · Channels: ${channels} · Seen: ${g.firstSeen} → ${g.lastSeen}`,
    `- How a report is placed: \`src/lib/kb/problems.ts\`. kb page: [\`${PAGE}\`](https://github.com/${repo}/blob/main/${PAGE}), rendered: [\`site/kb/incidents/4471/split/index.html\`](https://github.com/${repo}/blob/main/site/kb/incidents/4471/split/index.html).`,
    '- Generated by `scripts/sync-issues.ts` from `src/lib/data`; rerun after a new export.',
    '',
    `<details><summary>The ${g.reports.length} reports</summary>`,
    '',
    '| id | tenant | channel | received | report |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '</details>',
  ].join('\n');
}

type Issue = { number: number; title: string; body: string; state: string };
function find(p: Problem): Issue | undefined {
  const found: Issue[] = JSON.parse(
    gh('issue', 'list', '--repo', repo, '--state', 'all', '--label', label(p), '--json', 'number,title,body,state'),
  );
  return found.sort((a, b) => a.number - b.number)[0];
}

const check = process.argv.includes('--check');
const tickets: Partial<Record<Problem, number>> = {};
let stale = 0;

for (const p of PROBLEMS) {
  const g = split.groups.find((x) => x.problem === p);
  const issue = find(p);
  if (!g) {
    if (issue) console.log(`${p}: no reports left, issue #${issue.number} still exists`);
    continue;
  }
  const title = titleOf(g);
  const body = bodyOf(g);
  if (issue && issue.title === title && issue.body.trim() === body.trim()) {
    console.log(`${p}: #${issue.number} up to date (${g.reports.length} reports)`);
    tickets[p] = issue.number;
    continue;
  }
  stale++;
  if (check) {
    console.log(`${p}: ${issue ? `#${issue.number} out of date` : 'no issue'} (data: ${g.reports.length} reports)`);
    continue;
  }
  const file = new URL(`../.issue-${p}.md`, import.meta.url);
  fs.writeFileSync(file, body);
  if (issue) {
    gh('issue', 'edit', String(issue.number), '--repo', repo, '--title', title, '--body-file', file.pathname);
    tickets[p] = issue.number;
    console.log(`${p}: #${issue.number} updated (${g.reports.length} reports)`);
  } else {
    gh('label', 'create', label(p), '--repo', repo, '--force', '--color', 'b4501f', '--description', `#${TICKET} split: ${p}`);
    const url = gh('issue', 'create', '--repo', repo, '--title', title, '--body-file', file.pathname, '--label', label(p)).trim();
    tickets[p] = Number(url.split('/').pop());
    console.log(`${p}: ${url} created (${g.reports.length} reports)`);
  }
  fs.rmSync(file);
}

if (split.unplaced.length) console.log(`unplaced: ${split.unplaced.length} reports have no tenant cause`);
if (!check) fs.writeFileSync(new URL('tickets.json', DATA), JSON.stringify(tickets, null, 2) + '\n');
process.exit(check && stale ? 1 : 0);
